const ownerReq = (path: string, body?: Uint8Array | object, { origin = base as string | null, cookie = owner, type = "application/octet-stream" } = {}) =>
  new Request(base + path, {
    method: body === undefined ? "GET" : "POST",
    headers: { ...(cookie ? { cookie } : {}), ...(origin ? { origin } : {}), "content-type": body instanceof Uint8Array ? type : "application/json" },
    body: body === undefined ? undefined : body instanceof Uint8Array ? new Blob([new Uint8Array(body)]) : JSON.stringify(body),
  });
const wadeReq = (path: string, body?: object, { token = TOKEN, origin = null as string | null } = {}) =>
  new Request(base + path, {
    method: body === undefined ? "GET" : "POST",
    headers: { ...(token ? { authorization: `Bearer ${token}` } : {}), ...(origin ? { origin } : {}), ...(body ? { "content-type": "application/json" } : {}) },
    body: body === undefined ? undefined : JSON.stringify(body),
  });

